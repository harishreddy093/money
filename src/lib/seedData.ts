function makeRelativeIso(daysAgo: number, hour: number, minute: number): string {
  const now = new Date();
  const d = new Date(
    now.getFullYear(),
    now.getMonth(),
    now.getDate() - daysAgo,
    hour,
    minute,
    0,
    0
  );
  return d.toISOString();
}

